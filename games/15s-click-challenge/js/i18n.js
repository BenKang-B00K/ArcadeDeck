function detect() {
  const q = new URLSearchParams(location.search).get('lang');
  if (STR[q]) return q;
  for (const l of navigator.languages || [navigator.language || 'en']) {
    const base = l.slice(0, 2).toLowerCase();
    if (STR[base]) return base;
  }
  return 'en';
}

export const LANG = detect();

const plural = new Intl.PluralRules(LANG);
const num = new Intl.NumberFormat(LANG);

// t('startLevel', 3) → 'Start Level 3'. Numbers go through Intl.NumberFormat; unknown keys
// fall back to English, then to the key itself.
export function t(key, ...args) {
  let s = STR[LANG][key] ?? STR.en[key] ?? key;
  if (typeof s === 'object') s = s[plural.select(Number(args[0]))] ?? s.other;
  return s.replace(/\{(\d+)\}/g, (_, i) => {
    const v = args[i];
    return typeof v === 'number' ? num.format(v) : String(v);
  });
}

export function applyI18n() {
  document.documentElement.lang = LANG;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}

// Load-time check: every locale must define every English key.
for (const l of Object.keys(STR)) {
  const missing = Object.keys(STR.en).filter((k) => !(k in STR[l]));
  if (missing.length) console.warn(`i18n: "${l}" missing keys: ${missing.join(', ')}`);
}
