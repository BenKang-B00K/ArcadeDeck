const saved = (() => { try { return localStorage.getItem('lang'); } catch { return null; } })();
let cur = dict[saved] ? saved : dict[navigator.language?.slice(0, 2)] ? navigator.language.slice(0, 2) : 'en';

export const getLang = () => cur;
export const t = (k, v = {}) => (dict[cur][k] ?? dict.en[k] ?? k).replace(/\{(\w+)\}/g, (_, n) => v[n] ?? '');

export function applyI18n() {
  document.documentElement.lang = cur;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.title = t(el.dataset.i18nAria); el.setAttribute('aria-label', el.title); });
  document.querySelectorAll('[data-i18n-label]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nLabel)); }); // no title: the element draws its own tooltip
}

export function setLang(l) {
  if (!dict[l]) return;
  cur = l;
  try { localStorage.setItem('lang', l); } catch {}
  applyI18n();
}
